"use client";

import { useState, type FormEvent } from "react";
import { z } from "zod";
import { MEDICINE_FORMS } from "@/lib/constants";
import { createSupabaseBrowserClient } from "@/lib/supabase/browser";

const inventoryInput = z.object({
  name: z.string().trim().min(2).max(120),
  active_ingredient: z.string().trim().max(120).optional(),
  strength: z.string().trim().max(60).optional(),
  form: z.string().trim().max(40).optional(),
  status: z.enum(["in_stock", "unavailable", "unknown"]),
});

export function StaffInventoryPanel({ pharmacyId, pharmacyName }: { pharmacyId: string; pharmacyName: string }) {
  const [message, setMessage] = useState("");
  const [success, setSuccess] = useState(false);
  const [busy, setBusy] = useState(false);

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const currentForm = event.currentTarget;
    const client = createSupabaseBrowserClient();
    if (!client) { setSuccess(false); setMessage("Supabase is not configured; no inventory was changed."); return; }
    const formData = new FormData(currentForm);
    const parsed = inventoryInput.safeParse({
      name: formData.get("name"), active_ingredient: formData.get("active_ingredient") || undefined,
      strength: formData.get("strength") || undefined, form: formData.get("form") || undefined, status: formData.get("status"),
    });
    if (!parsed.success) { setSuccess(false); setMessage(parsed.error.issues[0]?.message ?? "Please check the medicine details."); return; }

    setBusy(true); setMessage("");
    const medicine = parsed.data;
    const matching = await client.from("medicine_catalog").select("id")
      .eq("name", medicine.name).eq("strength", medicine.strength ?? "").eq("form", medicine.form ?? "").limit(1).maybeSingle();
    let medicineId = matching.data?.id;
    if (matching.error) { setBusy(false); setSuccess(false); setMessage("Medicine catalog could not be searched. Try again."); return; }
    if (!medicineId) {
      const { data, error } = await client.from("medicine_catalog").insert({
        name: medicine.name, active_ingredient: medicine.active_ingredient || null,
        strength: medicine.strength || "", form: medicine.form || "", is_active: true,
      }).select("id").single();
      if (error) { setBusy(false); setSuccess(false); setMessage("This medicine could not be added. If it already exists, check the spelling or ask an administrator to review the catalog."); return; }
      medicineId = data.id;
    }
    const { error } = await client.from("inventory_confirmations").upsert({
      pharmacy_id: pharmacyId, medicine_id: medicineId, status: medicine.status, source: "pharmacy_staff",
    }, { onConflict: "pharmacy_id,medicine_id" });
    setBusy(false);
    if (error) { setSuccess(false); setMessage("Availability could not be saved. Check that this account is linked to the right pharmacy and try again."); return; }
    setSuccess(true);
    setMessage(`Confirmation recorded for ${pharmacyName}. Its timestamp and expiry were set automatically.`);
    currentForm.reset();
  }

  return (
    <form onSubmit={submit}>
      <div className="form-grid">
        <div className="field"><label htmlFor="medicine-name">Medicine name</label><input id="medicine-name" name="name" required maxLength={120} /></div>
        <div className="field"><label htmlFor="active-ingredient">Active ingredient <span style={{ fontWeight: 400 }}>(optional)</span></label><input id="active-ingredient" name="active_ingredient" maxLength={120} /></div>
        <div className="field"><label htmlFor="strength">Strength or dosage</label><input id="strength" name="strength" placeholder="e.g. 250 mg" maxLength={60} /></div>
        <div className="field"><label htmlFor="medicine-form">Form</label><select id="medicine-form" name="form" defaultValue=""><option value="">Choose form</option>{MEDICINE_FORMS.map((item) => <option key={item} value={item}>{item}</option>)}</select></div>
        <div className="field"><label htmlFor="availability-status">Availability</label><select id="availability-status" name="status" defaultValue="unknown"><option value="in_stock">In stock</option><option value="unavailable">Unavailable</option><option value="unknown">Unknown</option></select></div>
      </div>
      <div style={{ marginTop: 16 }}><button className="button button-primary" type="submit" disabled={busy}>{busy ? "Saving…" : "Record confirmation"}</button></div>
      {message && <p className={success ? "form-success" : "form-error"} role="status">{message}</p>}
      <p className="auth-footnote">Only record information that the pharmacy has genuinely checked. Every update is linked to this pharmacy and staff session; confirmation time and expiry are generated by the database.</p>
    </form>
  );
}
